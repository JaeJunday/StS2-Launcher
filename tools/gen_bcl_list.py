#!/usr/bin/env python3
"""Generate BclAssets.g.cs from the base APK's assets/dotnet_bcl listing.

The launcher's Java layer copies every file in assets/dotnet_bcl into
files/.godot/mono/publish/arm64 as the Android Mono "BCL" set. The depot also
ships desktop CoreCLR copies of some of those same names, which must never be
allowed to overwrite the Android ones, so the C# maintenance code needs to know
exactly which names came from the APK.

Usage: tools/gen_bcl_list.py <base.apk> <out.cs>
"""
import sys
import zipfile

PREFIX = "assets/dotnet_bcl/"


def main() -> int:
    apk, out = sys.argv[1], sys.argv[2]
    with zipfile.ZipFile(apk) as z:
        names = sorted(
            n[len(PREFIX):] for n in z.namelist()
            if n.startswith(PREFIX) and n.endswith(".dll")
        )
    lines = [
        "// <auto-generated>",
        "// Generated by tools/gen_bcl_list.py from the packaged assets/dotnet_bcl set.",
        "// Do not edit by hand; re-run the generator when the base APK changes.",
        "// </auto-generated>",
        "using System.Collections.Generic;",
        "",
        "namespace STS2Mobile.Maintenance;",
        "",
        "public static class BclAssets",
        "{",
        "    // Names owned by the Android Mono runtime bundled with the APK.",
        "    public static readonly IReadOnlySet<string> FileNames = new HashSet<string>(",
        "        System.StringComparer.OrdinalIgnoreCase",
        "    )",
        "    {",
    ]
    lines += [f'        "{n}",' for n in names]
    lines += ["    };", "}", ""]
    with open(out, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    print(f"wrote {out} with {len(names)} names")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
